import { PGlite } from '@electric-sql/pglite';
import { readFile } from 'node:fs/promises';
import { test } from 'node:test';
import assert from 'node:assert/strict';

test('trainer workspaces enforce account ownership, role gates, atomic revisions, and exact retries', async () => {
  const db = new PGlite();
  const alice = '00000000-0000-4000-8000-000000000001';
  const bob = '00000000-0000-4000-8000-000000000002';
  const member = '00000000-0000-4000-8000-000000000003';
  const doc = { version: 1, business: { name: 'Alice studio', audience: '', offer: '', monthlyPrice: 200 }, clients: [], programs: [], assignments: [], checkIns: [], completedLessons: [], favoriteExercises: [] };
  try {
    await db.exec(`create role authenticated; create role anon; create schema auth;
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
      grant usage on schema public, auth to authenticated, anon;
      create table public.profiles(id uuid primary key, role text);
      insert into profiles values ('${alice}', 'coach'), ('${bob}', 'coach'), ('${member}', 'member');
      grant select on profiles to authenticated;`);
    await db.exec(await readFile(new URL('../supabase/migrations/20261012100000_trainer_hub.sql', import.meta.url), 'utf8'));
    await db.exec('set role authenticated');
    const identity = id => db.query("select set_config('request.jwt.claim.sub', $1, false)", [id]);
    const save = (document, revision, mutation) => db.query('select save_trainer_hub_workspace($1::jsonb, $2, $3::uuid) as result', [JSON.stringify(document), revision, mutation]);
    await identity(alice);
    const mutation = crypto.randomUUID();
    const first = (await save(doc, 0, mutation)).rows[0].result;
    assert.equal(first.revision, 1);
    assert.deepEqual((await save(doc, 0, mutation)).rows[0].result, first, 'lost-response retry retains revision and original data');
    await assert.rejects(save({ ...doc, business: { ...doc.business, name: 'Changed retry' } }, 0, mutation), e => e.code === '23505');
    const secondDoc = { ...doc, completedLessons: ['first-client'] };
    await save(secondDoc, 1, crypto.randomUUID());
    await assert.rejects(save(doc, 1, crypto.randomUUID()), e => e.code === '40001');
    await assert.rejects(save({}, 2, crypto.randomUUID()), e => e.code === '23514', 'malformed direct RPC payload rolls back');
    assert.equal((await db.query('select revision from trainer_hub_workspaces')).rows[0].revision, 2);
    await assert.rejects(db.query('update trainer_hub_workspaces set revision = 900 where owner_id = $1', [alice]), e => e.code === '42501', 'direct table writes cannot skip optimistic revision checks');
    await identity(bob);
    assert.equal((await db.query('select * from trainer_hub_workspaces')).rows.length, 0);
    const bobDoc = { ...doc, business: { ...doc.business, name: 'Bob studio' } };
    await save(bobDoc, 0, crypto.randomUUID());
    assert.equal((await db.query('select * from trainer_hub_workspaces')).rows[0].owner_id, bob);
    await identity(member);
    assert.equal((await db.query('select * from trainer_hub_workspaces')).rows.length, 0);
    await assert.rejects(save(doc, 0, crypto.randomUUID()), e => e.code === '42501');
    await identity(alice);
    await db.exec('reset role');
    await db.query("update profiles set role = 'member' where id = $1", [alice]);
    await db.exec('set role authenticated');
    assert.equal((await db.query('select * from trainer_hub_workspaces')).rows.length, 0, 'role revocation also removes read access');
    await assert.rejects(save(doc, 2, crypto.randomUUID()), e => e.code === '42501');
    await db.exec('set role anon');
    await assert.rejects(save(doc, 0, crypto.randomUUID()), e => e.code === '42501');
  } finally { await db.close(); }
});
