import {PGlite} from '@electric-sql/pglite';
import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {test} from 'node:test';
test('publishing isolates drafts, snapshots revisions and rejects stale or unauthorized writes',async()=>{
 const db=new PGlite();
 try{
  await db.exec(`create role authenticated;create role anon;create schema auth;
   create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
   create function auth.jwt() returns jsonb language sql stable as $$select '{}'::jsonb$$;
   create table auth.mfa_factors(user_id uuid,status text);
   create table profiles(id uuid,role text);
   create table fitness_program_versions(program_id text,version integer,definition jsonb);
   insert into profiles values('00000000-0000-4000-8000-000000000001','admin');
   grant usage on schema public,auth to authenticated,anon;grant select on profiles to authenticated;`);
  for(const file of ['20261104150000_app_content_banks.sql','20261104160000_content_publications.sql','20261105180000_news_content_bank.sql'])await db.exec(await readFile(new URL('../supabase/migrations/'+file,import.meta.url),'utf8'));
  await db.exec('set role anon');
  assert.equal((await db.query('select * from app_content_publications')).rows.length,0);
  await assert.rejects(db.query('select * from app_content_drafts'),/permission denied/);
  await assert.rejects(db.query('select publish_app_content(null,1)'),/permission denied/);
  await db.exec("set role authenticated;select set_config('request.jwt.claim.sub','00000000-0000-4000-8000-000000000001',false)");
  const newsFields={Kind:'event',Topic:'community','Image URL':'/onboarding-location-outdoors-travel.jpg','Published at':'2026-11-05T12:00:00-08:00','Starts at':'2026-12-01T10:00:00-08:00',Location:'Studio'};
  const news=(await db.query("select * from save_app_content_draft(null,'news','Community event','Summary',$1,0)",[JSON.stringify(newsFields)])).rows[0];
  await db.query('select publish_app_content($1,1)',[news.id]);
  assert.equal((await db.query("select fields->>'Image URL' as photo from app_content_publications where bank='news'")).rows[0].photo,newsFields['Image URL']);
  const invalid=(await db.query("select * from save_app_content_draft(null,'news','Missing photo','Summary',$1,0)",[JSON.stringify({...newsFields,'Image URL':''})])).rows[0];
  await assert.rejects(db.query('select publish_app_content($1,1)',[invalid.id]),/photo URL/);
  await db.exec('reset role');
  await db.query('delete from app_content_history where entry_id=$1',[news.id]);
  await db.query('delete from app_content_publications where id=$1',[news.id]);
  await db.exec('set role authenticated');
  const save="select * from save_app_content_draft($1,'chyron',$2,'summary',$3,$4)";
  const entry=(await db.query(save,[null,'First',JSON.stringify({Message:'Original'}),0])).rows[0];
  await db.query('select * from publish_app_content($1,1)',[entry.id]);
  await db.query(save,[entry.id,'Edited',JSON.stringify({Message:'Draft only'}),1]);
  assert.equal((await db.query('select title from app_content_publications')).rows[0].title,'First');
  await assert.rejects(db.query('select * from publish_app_content($1,1)',[entry.id]),/draft changed/);
  await db.query('select * from publish_app_content($1,2)',[entry.id]);
  await db.query('select * from publish_app_content($1,2)',[entry.id]);
  assert.equal((await db.query('select count(*)::int as n from app_content_history')).rows[0].n,2);
  assert.equal((await db.query('select title from app_content_publications')).rows[0].title,'Edited');
  await db.query(save,[entry.id,'Unsafe',JSON.stringify({Message:'Hello','Image URL':'javascript:alert(1)'}),2]);
  await assert.rejects(db.query('select * from publish_app_content($1,3)',[entry.id]),/HTTPS/);
  await db.exec("select set_config('request.jwt.claim.sub','00000000-0000-4000-8000-000000000002',false)");
  await assert.rejects(db.query('select * from publish_app_content($1,3)',[entry.id]),/Admin access/);
  await db.exec('set role anon');
  assert.equal((await db.query('select title from app_content_publications')).rows[0].title,'Edited');
 }finally{await db.close();}
});
